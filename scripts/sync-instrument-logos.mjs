const jobs=[...MARKET_ASSETS.thai.map(a=>({...a,market:'thai',ticker:`${a.symbol}.BK`})),
 ...MARKET_ASSETS.dr.filter(a=>dr[a.symbol]).map(a=>({...a,market:'dr',ticker:dr[a.symbol]}))];
const entries={},failures=[];
const previous=await readFile('public/instrument-logos/sources.json','utf8').then(JSON.parse).catch(()=>({entries:{}}));
async function download(a){
 const source=`https://financialmodelingprep.com/image-stock/${encodeURIComponent(a.ticker)}.png`;
 const identitySource=`https://www.set.or.th/en/market/${a.market==='dr'?'product/dr':'product/stock'}/quote/${a.symbol}/company-profile`;
 try{
  const url=`/instrument-logos/${a.market}/${a.symbol}.png`;
  let bytes=previous.entries[`${a.market}:${a.symbol}`]?.source===source&&!process.argv.includes('--refresh')?await readFile(`public${url}`).catch(()=>null):null;
  if(!bytes&&a.market==='dr'){
   const r=await fetch(identitySource,{signal:AbortSignal.timeout(20000)});
   const html=await r.text();
   if(!r.ok||!html.includes(`symbol:"${a.symbol}"`)||!html.match(/underlying:"[^"]+"/))throw Error('IDENTITY_UNAVAILABLE');
  }
  if(!bytes){
   const r=await fetch(source,{signal:AbortSignal.timeout(20000)});
   if(!r.ok)throw Error(`IMAGE_${r.status}`);
   bytes=Buffer.from(await r.arrayBuffer());
  }
  if(bytes.length>2_000_000||bytes.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw Error('INVALID_IMAGE');
  const {data,info}=await sharp(bytes,{limitInputPixels:4_000_000}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  let luminance=0,weight=0;
  for(let i=0;i<data.length;i+=info.channels){const alpha=data[i+3];luminance+=(data[i]*.2126+data[i+1]*.7152+data[i+2]*.0722)*alpha;weight+=alpha;}
  // White artwork on transparent pixels needs a dark matte, e.g. Nike.
  const background=weight&&luminance/weight>220?'#172b4d':'#ffffff';
  await mkdir(`public/instrument-logos/${a.market}`,{recursive:true});
  await writeFile(`public${url}`,bytes);
  entries[`${a.market}:${a.symbol}`]={url,background,companyImageTicker:a.ticker,source,identitySource};
 }catch(e){failures.push({market:a.market,symbol:a.symbol,code:e.message});}
}
// Four bounded requests at a time; this never runs in the market-data worker.
let index=0;await Promise.all(Array.from({length:4},async()=>{while(index<jobs.length)await download(jobs[index++]);}));
const sorted=Object.fromEntries(Object.entries(entries).sort(([a],[b])=>a.localeCompare(b)));
await writeFile('src/markets/local-logos.mjs',`// Generated by scripts/sync-instrument-logos.mjs. Brand images remain their owners' property.\nexport const LOCAL_INSTRUMENT_LOGOS = Object.freeze(${JSON.stringify(sorted,null,2)});\n`);
await writeFile('public/instrument-logos/sources.json',JSON.stringify({updatedAt:new Date().toISOString(),entries:sorted,unavailable:failures},null,2)+'\n');
console.log(JSON.stringify({thai:Object.keys(entries).filter(k=>k.startsWith('thai:')).length,dr:Object.keys(entries).filter(k=>k.startsWith('dr:')).length,unavailable:failures}));
